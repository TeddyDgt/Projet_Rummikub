static const unsigned char *glyph_5x7(char c) {
    if (c == ' ') {
        return FONT_SPACE;
    }
    if (c == '-') {
        return FONT_DASH;
    }
    if (c == '+') {
        return FONT_PLUS;
    }
    if (c >= '0' && c <= '9') {
        return FONT_DIGITS[c - '0'];
    }
    c = (char)toupper((unsigned char)c);
    if (c >= 'A' && c <= 'Z') {
        return FONT_LETTERS[c - 'A'];
    }
    return FONT_SPACE;
}

float ui_text_width(const char *text, float scale) {
    if (!text || !*text) {
        return 0.0f;
    }
    return (float)(strlen(text) * 6 - 1) * scale;
}

float ui_text_height(float scale) {
    return 7.0f * scale;
}

void ui_draw_text(float x, float y, float scale, const char *text,
                  float r, float g, float b, float a) {
    if (!text) {
        return;
    }
    float pen_x = x;
    for (const char *p = text; *p; p++) {
        const unsigned char *glyph = glyph_5x7(*p);
        for (int row = 0; row < 7; row++) {
            unsigned char row_bits = glyph[row];
            for (int col = 0; col < 5; col++) {
                if (row_bits & (1u << (4 - col))) {
                    float px = pen_x + (float)col * scale;
                    float py = y + (float)row * scale;
                    r2d_fill_rect(px, py, scale, scale, r, g, b, a);
                }
            }
        }
        pen_x += 6.0f * scale;
    }
}

void ui_draw_text_centered(Rect r, float scale, const char *text,
                           float cr, float cg, float cb, float ca) {
    float tw = ui_text_width(text, scale);
    float th = ui_text_height(scale);
    float tx = r.x + (r.w - tw) * 0.5f;
    float ty = r.y + (r.h - th) * 0.5f;
    ui_draw_text(tx, ty, scale, text, cr, cg, cb, ca);
}
